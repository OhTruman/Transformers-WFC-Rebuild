# Generates src/game/WeaponCameraTable.inc: per weapon class, the camera recoil and per-shot shake the local player's camera applies
# (TnRecoilCameraBehavior / TnShakeCameraBehavior; RE WEAPON_CAMERA_SHAKE_RE.md section 4).
# Source: AssetTools authored.db (the weapon class CDOs, TransGame / TransContent.Default__TnWeapon<id>, and their TnWeaponData objects),
# so every weapon class gets its row (data/gameplay/weapons_mp.json lacked classes such as TnWeaponEMPShotgun).
# Data selection (TnWeapon.GivenTo, CONFIRMED): TnMultiplayerGame wants MultiplayerData; a class without one uses PlayerData WHOLE (no
# per-field merge); fields missing in the chosen object are 0 (the struct defaults).
# Usage: python -I tools/gameplay/gen_weapon_camera.py <authored.db> <out.inc>
import json, sqlite3, sys

def main(db, out):
    c = sqlite3.connect('file:%s?mode=ro' % db, uri=True)
    def props(o):
        r = c.execute('select props from objects where opath = ?', (o,)).fetchone()
        return json.loads(r[0] or '{}') if r else {}
    rows = {}
    for opath, pr in c.execute("select opath, props from objects where opath like 'Trans%.Default__TnWeapon%'"):
        wid = opath.split('.Default__TnWeapon', 1)[1]
        if not wid or '.' in wid: continue
        p = json.loads(pr or '{}')
        mp = p.get('MultiplayerData')
        src = mp or p.get('PlayerData')
        if not src: continue
        data = props(src)
        r = data.get('RecoilCameraParams') or {}
        s = data.get('CameraShakeParams') or {}
        row = (wid, r.get('PitchAdjustmentDeg', 0.0), r.get('FovAdjustment', 0.0), r.get('RecoilTime', 0.0), r.get('RecoilDelay', 0.0),
               s.get('Intensity', 0.0), s.get('Roll', 0.0), s.get('RollFalloffDuration', 0.0), s.get('ShakeFalloffDuration', 0.0),
               'MultiplayerData' if mp else 'PlayerData')
        if any(abs(x) > 0 for x in row[1:9]): rows[wid] = row
    L = ['// GENERATED by tools/gameplay/gen_weapon_camera.py from AssetTools authored.db - do not edit. Per weapon class suffix',
         '// (TnWeapon<id>): RecoilCameraParams {PitchAdjustmentDeg, FovAdjustment, RecoilTime, RecoilDelay} and CameraShakeParams',
         '// {Intensity, Roll, RollFalloffDuration, ShakeFalloffDuration} of MultiplayerData, else PlayerData (whole object); missing fields 0.']
    for wid in sorted(rows):
        L.append('    {"%s", %.4ff, %.4ff, %.4ff, %.4ff, %.4ff, %.4ff, %.4ff, %.4ff},   // %s' % rows[wid])
    open(out, 'w', newline='\n').write('\n'.join(L) + '\n')
    print(len(rows), 'weapons ->', out)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
