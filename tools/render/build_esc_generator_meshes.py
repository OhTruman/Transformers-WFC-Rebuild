"""Escalation generator meshes (user playtest 2026-10-24c: the purchasable doors / vending machines had no presentation - the
TnSurvivalGenerator actors are skeletal (HmLightMappedSkeletalMeshComponent), and world.glb carries no skeletal actors). For every
Escalation map: each TnSurvivalGenerator's SkeletalMesh (the component's, else the class default AP_VendingMachine_SKEL), its
component Materials overrides, and the actor transform -> src/game/EscGeneratorMeshes.inc (compiled in, as EscalationData.inc).

  python tools/render/build_esc_generator_meshes.py [out .inc]
"""
import json, os, sqlite3, sys

AT = "F:/Transformers Rebuild/AssetTools/manifests/"
MAPS = [("MP_ESC_BrokenHope", "MP_ESC_BrokenHope_BASE_m", "authored.db"), ("MP_ESC_Remnant", "MP_Esc_Remnant_BASE_m", "authored.db"),
        ("MP_ESC_Tranquillity", "MP_ESC_Tranquillity_BASE_m", "dlc/authored.db"), ("MP_ESC_District", "MP_ESC_District_BASE_m", "dlc/authored.db"),
        ("MP_ESC_Pulse", "MP_ESC_Pulse_Base_m", "dlc/authored.db"), ("MP_ESC_Static", "MP_ESC_Static_BASE_m", "dlc/authored.db")]
DEFAULT_MESH = "PROP_VendingMachine_p.AP_VendingMachine_SKEL"   # TnSurvivalGenerator's class default (no component SkeletalMesh)
CONTENT = "F:/Transformers Rebuild/ExtractedAssets/content/"


def gltf_of(obj):   # "Pkg.Group.Name" -> "Pkg/Group/Name.gltf" under content/
    parts = obj.split(".")
    return "/".join(parts) + ".gltf"


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/game/EscGeneratorMeshes.inc"
    rows = []
    for mapName, level, db in MAPS:
        c = sqlite3.connect("file:%s%s?mode=ro" % (AT, db), uri=True)
        lv = c.execute("select opath from objects where lower(opath) like lower(?) limit 1", (level + ".TheWorld.PersistentLevel.%",)).fetchone()
        if not lv:
            print("no level", level); continue
        P = lv[0][:lv[0].index(".TheWorld.PersistentLevel.") + len(".TheWorld.PersistentLevel.")]
        n = 0
        for g, props in c.execute("select opath, props from objects where opath like ? and class = 'TnSurvivalGenerator'", (P + "%",)):
            if "." in g[len(P):]: continue
            d = json.loads(props or "{}")
            mesh, mats = None, []
            for o, cp in c.execute("select opath, props from objects where opath like ?", (g + ".%",)):
                cd = json.loads(cp or "{}")
                if "SkeletalMesh" in cd: mesh = cd["SkeletalMesh"]
                if "Materials" in cd and isinstance(cd["Materials"], list): mats = cd["Materials"]
                elif "Materials" in cd and isinstance(cd["Materials"], str):
                    try: mats = json.loads(cd["Materials"].replace("'", '"').replace("None", "null"))
                    except Exception: mats = []
            mesh = mesh or DEFAULT_MESH
            gl = gltf_of(mesh)
            if not os.path.exists(CONTENT + gl):
                print("  missing mesh", mapName, g.split(".")[-1], gl); continue
            L = d.get("Location") or {}
            if isinstance(L, str): L = json.loads(L.replace("'", '"'))
            R = d.get("Rotation") or {}
            if isinstance(R, str): R = json.loads(R.replace("'", '"'))
            s = float(d.get("DrawScale") or 1.0)
            ue = [float(L.get("X", 0)), float(L.get("Y", 0)), float(L.get("Z", 0))]
            pos = [ue[0] * 0.01, ue[2] * 0.01, ue[1] * 0.01]   # glTF metres, Y-up
            yaw = float(R.get("Yaw", 0)) * 360.0 / 65536.0
            m3 = [(m or "") for m in (mats + [None, None, None, None])[:4]]
            rows.append((mapName, g.split(".")[-1], gl, m3, pos, yaw, s, float(R.get("Pitch", 0)) != 0 or float(R.get("Roll", 0)) != 0))
            n += 1
        print(mapName, n, "generators")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/render/build_esc_generator_meshes.py from AssetTools authored.db (base + dlc); do not edit.\n")
        f.write("// Escalation TnSurvivalGenerator presentation: map, actor, mesh glTF (content-relative), component material overrides by\n")
        f.write("// slot (\"\" = the mesh's own), position (glTF metres), yaw (deg, UE sense), DrawScale.\n")
        f.write("static const EscGeneratorMesh kEscGeneratorMeshes[] = {\n")
        for mapName, actor, gl, m3, pos, yaw, s, tilted in rows:
            f.write('    {"%s", "%s", "%s", {"%s", "%s", "%s", "%s"}, {%.4ff, %.4ff, %.4ff}, %.4ff, %.4ff},%s\n' % (
                mapName, actor, gl, m3[0], m3[1], m3[2], m3[3], pos[0], pos[1], pos[2], yaw, s, "   // (pitch / roll authored: not applied)" if tilted else ""))
        f.write("};\n")
    print("wrote", out, len(rows), "rows")


if __name__ == "__main__":
    main()
