# Generates src/game/GibRagdollTable.inc from AssetTools/manifests/authored.db (read only): the robot skeletal gibs' physics assets
# (TR_Death_Gibs_p.Skeletal.GIB_Body_PHYSSYS / GIB_LowBody2_PHYSSYS: RB_BodySetup shapes, RB_ConstraintSetup swing / twist limits),
# converted to the rebuild's bone frames: the glTF export keeps each UE bone frame with Y and Z swapped (glTF = (X, Z, Y)), in
# metres. Shape TMs are UE FMatrix rows printed as FPlanes (W first): row 2 = the sphyl axis, row 3 = the centre (UU).
# Constraint axes default to UE PriAxis (1,0,0) / SecAxis (0,1,0); an absent limit angle is 0 (locked).
# Usage: python -I tools/gameplay/gen_gib_ragdoll.py <authored.db> <out.inc>
import json, sqlite3, sys

def sw(v):  # UE (X, Y, Z) -> rebuild bone frame (X, Z, Y)
    return (v[0], v[2], v[1])

def plane(tm, i):  # FPlane i of a 16-float TM printed (W, X, Y, Z)
    return (tm[4 * i + 1], tm[4 * i + 2], tm[4 * i + 3])

def vec(d, k, dflt):
    v = d.get(k)
    return (v['X'], v['Y'], v['Z']) if v else dflt

def f(x):
    return '%.6ff' % x

def main(db, out):
    c = sqlite3.connect('file:%s?mode=ro' % db, uri=True)
    lines = ['// GENERATED by tools/gameplay/gen_gib_ragdoll.py - do not edit. Robot skeletal gibs (TnSkeletalGibSpawner SharedRobotDeaths',
             '// templates): per body {bone, shapes {sphere 0 / capsule 1, centre m, axis, radius m, half length m}}; per constraint',
             '// {child bone, parent bone, swing1 / swing2 / twist limit deg (0 = locked), soft (limit stiffness authored), twist axis, swing',
             '// axis (child bone frame)}. Bone frames as the glTF export (UE axes with Y / Z swapped), metres.']
    for gib in ('GIB_Body', 'GIB_LowBody2'):
        pa = 'TR_Death_Gibs_p.Skeletal.%s_PHYSSYS' % gib
        bodies, cons = [], []
        for opath, cls, props in c.execute("select opath, class, props from objects where opath like ? order by opath", (pa + '.RB_%',)):
            p = json.loads(props)
            if cls == 'RB_BodySetup':
                shapes = []
                for kind, elems in p.get('AggGeom', {}).items():
                    for e in elems:
                        tm = e['TM']
                        ctr = tuple(x * 0.01 for x in sw(plane(tm, 3)))
                        if kind == 'SphereElems': shapes.append((0, ctr, (0.0, 0.0, 1.0), e['Radius'] * 0.01, 0.0))
                        elif kind == 'SphylElems': shapes.append((1, ctr, sw(plane(tm, 2)), e['Radius'] * 0.01, e['Length'] * 0.005))
                        else: raise SystemExit('unhandled shape kind %s in %s' % (kind, opath))
                bodies.append((p['BoneName'], shapes))
            elif cls == 'RB_ConstraintSetup':
                cons.append((p['ConstraintBone1'], p['ConstraintBone2'], p.get('Swing1LimitAngle', 0.0), p.get('Swing2LimitAngle', 0.0),
                             p.get('TwistLimitAngle', 0.0), 1 if 'SwingLimitStiffness' in p else 0,
                             sw(vec(p, 'PriAxis1', (1.0, 0.0, 0.0))), sw(vec(p, 'SecAxis1', (0.0, 1.0, 0.0)))))
        bodies.sort(); cons.sort()
        lines.append('static const GibBodyDef k%sBodies[] = {' % gib.replace('GIB_', ''))
        for bone, shapes in bodies:
            sh = ', '.join('{%d, {%s, %s, %s}, {%s, %s, %s}, %s, %s}' % (k, f(ct[0]), f(ct[1]), f(ct[2]), f(ax[0]), f(ax[1]), f(ax[2]), f(r), f(h))
                           for k, ct, ax, r, h in shapes)
            lines.append('    {"%s", %d, {%s}},' % (bone, len(shapes), sh))
        lines.append('};')
        lines.append('static const GibJointDef k%sJoints[] = {' % gib.replace('GIB_', ''))
        for a, b, s1, s2, tw, soft, pri, sec in cons:
            lines.append('    {"%s", "%s", %s, %s, %s, %d, {%s, %s, %s}, {%s, %s, %s}},' % (a, b, f(s1), f(s2), f(tw), soft,
                         f(pri[0]), f(pri[1]), f(pri[2]), f(sec[0]), f(sec[1]), f(sec[2])))
        lines.append('};')
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote', out)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
