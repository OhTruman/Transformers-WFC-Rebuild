"""The original's death entries for the presentation-only corpses (GAMEPLAY_DEATH_BODY_DESIGN.md), from AssetTools' authored.db (read only):
TR_Deaths_p.Shared{Robot,Car,Tank,Jet}Deaths TnDeathBlueprint entries (Types, Animation.AnimationName / BlendInTime, TotalTime, TotalTimeForAI,
modifier kinds) in authored order (TnDeathPicker.Pick takes the first entry whose Types are all active), and every TnDamageType's
DamageDeathType resolved through the class hierarchy (a subclass inherits its parent's default).
argv[1] = output .inc (src/game/DeathEntries.inc)."""
import sqlite3, json, sys

db = sqlite3.connect('file:F:/Transformers Rebuild/AssetTools/manifests/authored.db?mode=ro', uri=True)

def props(path):
    r = db.execute("select props from objects where opath=? limit 1", (path,)).fetchone()
    return json.loads(r[0]) if r and r[0] else {}

def cls_of(path):
    r = db.execute("select class from objects where opath=? limit 1", (path,)).fetchone()
    return r[0] if r else ''

MOD_BITS = {'TnDeathModifierControlBone': 1, 'TnDeathModifierSetMaterial': 2, 'TnDeathModifierPlayEffect': 4,
            'TnDeathModifierTriggerLight': 8, 'TnDeathModifierApplyForce': 16, 'TnDeathModifierPlaySound': 32}

def short(t):
    return t.split('.')[-1].replace('TnDeathType', '') if t else ''

out = ['// GENERATED by tools/gameplay/death_entries.py from AssetTools authored.db (read only); do not edit.',
       '// TnDeathBlueprint entries in authored order: Types (short TnDeathType names), Animation, BlendInTime, TotalTime [min, max],',
       '// TotalTimeForAI [min, max] (0 = TotalTime), modifier bits (1 ControlBone head 0.1, 2 SetMaterial Defrag, 4 PlayEffect, 8 TriggerLight,',
       '// 16 ApplyForce, 32 PlaySound).']
for bp in ('SharedRobotDeaths', 'SharedCarDeaths', 'SharedTankDeaths', 'SharedJetDeaths'):
    d = props('TR_Deaths_p.' + bp)
    out.append(f'static const DeathEntryDef k{bp}[] = {{')
    for e in d.get('Deaths', []):
        types = [short(t) for t in e.get('Types', [])]
        anim = e.get('Animation', {}).get('AnimationName', 'None')
        bits = 0
        for m in e.get('Modifiers', []):
            bits |= MOD_BITS.get(cls_of(m), 0)
        tt, ta = e.get('TotalTime', {}), e.get('TotalTimeForAI', {})
        ts = ', '.join(f'"{t}"' for t in types) or '""'
        out.append(f'    {{{{{ts}}}, {len(types)}, "{"" if anim == "None" else anim}", {e.get("Animation", {}).get("BlendInTime", 0.2):.3f}f, '
                   f'{tt.get("Min", 1.0):.3f}f, {tt.get("Max", 1.0):.3f}f, {ta.get("Min", 0.0):.3f}f, {ta.get("Max", 0.0):.3f}f, {bits}u}},')
    out.append('};')

# DamageDeathType per damage type class, inherited through the class hierarchy.
supers = {p: s for p, s in db.execute("select path, super from types where kind='Class'")}
def death_type(cls, depth=0):
    if depth > 12 or not cls:
        return ''
    name = cls.split('.')[-1]
    p = props(cls.rsplit('.', 1)[0] + '.Default__' + name)
    if 'DamageDeathType' in p:
        return short(p['DamageDeathType'] or '')
    return death_type(supers.get(cls), depth + 1)

rows = []
for (path,) in db.execute("select path from types where kind='Class' and path like 'TransGame.TnDamageType%'"):
    rows.append((path, death_type(path)))
out.append('// Damage type class -> its DamageDeathType (short TnDeathType name; empty = none).')
out.append('static const DamageDeathTypeDef kDamageDeathTypes[] = {')
for path, t in sorted(rows):
    out.append(f'    {{"{path}", "{t}"}},')
out.append('};')
open(sys.argv[1], 'w', newline='\n').write('\n'.join(out) + '\n')
print(len(rows), 'damage types')

# Death chooser groups (AnimSet.ChooserGroups: the animator resolves an AnimName that is a group to a weighted pick of its anims;
# UE3 searches the mesh's AnimSets last first). Merged by group name over the death-relevant robot sets (first set wins per group);
# the runtime keeps the anims present in the chassis' model (a chassis without that set has none of its clips: no animation).
groups = {}
for o, p in db.execute("select opath, props from objects where class='AnimSet' and props like '%ChooserGroups%'"):
    d = json.loads(p)
    for g in d.get('ChooserGroups', []):
        n = g.get('GroupName')
        if n in ('ProjectileSingle', 'ProjectileMultiple', 'Explosion', 'InAir', 'EnergyRanged', 'Death_HeadShot', 'Death_FrontShot',
                 'Death_BackShot', 'Death_Martyrdom') and n not in groups:
            groups[n] = (o, [(a.get('AnimName'), a.get('Weight', 1)) for a in g.get('Anims', [])])
out2 = ['// Death chooser groups: group, anim, weight (source AnimSet in the comment).', 'static const DeathChooserDef kDeathChoosers[] = {']
for n in sorted(groups):
    src, anims = groups[n]
    for a, w in anims:
        out2.append(f'    {{"{n}", "{a}", {w}}},   // {src}')
out2.append('};')
open(sys.argv[1], 'a', newline='\n').write('\n'.join(out2) + '\n')
print(len(groups), 'chooser groups')

# Per chassis (ExtractedAssets/VerticalSlice/Characters/*/character.json): the robot / vehicle definitions' DeathBlueprint and the
# vehicle form's DefaultSkeletalGibTemplate (the hull wreck mesh, exported as content/<package>/<name>.gltf) + TransferVelocityMultiplier.
import glob, os
rows3 = []
for cj in sorted(glob.glob(r'F:/Transformers Rebuild/ExtractedAssets/VerticalSlice/Characters/*/character.json')):
    ch = json.load(open(cj, encoding='utf-8'))
    cid = ch.get('chassis_id') or os.path.basename(os.path.dirname(cj))
    rdef = (ch.get('robot') or {}).get('definition') or ''
    vdef = (ch.get('vehicle') or {}).get('definition') or ''
    rp, vp = props(rdef) if rdef else {}, props(vdef) if vdef else {}
    rd = (rp.get('DeathBlueprint') or '').split('.')[-1]
    vd = (vp.get('DeathBlueprint') or '').split('.')[-1]
    hull, mult = '', 0.0
    t = vp.get('DefaultSkeletalGibTemplate') or []
    if t and t[0].get('MeshTemplate'):
        pkg, name = t[0]['MeshTemplate'].split('.', 1)
        hull = f'content/{pkg}/{name}.gltf'
        mult = float(t[0].get('TransferVelocityMultiplier', 0.0) or 0.0)
    rows3.append((cid, rd, vd, hull, mult))
out3 = ['// Per chassis: robot DeathBlueprint, vehicle DeathBlueprint, hull wreck glTF (relative to ExtractedAssets), TransferVelocityMultiplier.',
        'static const ChassisDeathDef kChassisDeaths[] = {']
for cid, rd, vd, hull, mult in rows3:
    out3.append(f'    {{"{cid}", "{rd}", "{vd}", "{hull}", {mult:.2f}f}},')
out3.append('};')
open(sys.argv[1], 'a', newline='\n').write('\n'.join(out3) + '\n')
print(len(rows3), 'chassis')
