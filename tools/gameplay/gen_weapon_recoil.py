# Generates src/game/WeaponRecoilTable.inc: per weapon, the resolved SpineRecoil / RightHandRecoil (HmSkelControlRecoil) = the
# TransGame.Default__TnWeaponMesh archetype overlaid with the weapon mesh's authored members (RE weapon presentation audit,
# notes/data/weapon_presentation_audit.json; archetype from AssetTools authored.db). Overlay rule (UE3 tagged struct members): an authored
# vector member (TimeDuration, RotAmplitude, RotFrequency, LocAmplitude, LocFrequency) replaces the archetype's member whole; RotParams /
# LocParams override per axis (X / Y / Z enums). A weapon without authored recoil uses the archetype ("" row first).
# Usage: python -I gen_weapon_recoil.py <weapon_presentation_audit.json> <authored.db> <out.inc>
import json, sqlite3, sys

def vec(v, d):
    return (v.get('X', d[0]), v.get('Y', d[1]), v.get('Z', d[2])) if isinstance(v, dict) else d

def resolve(arch, ov):
    r = {'TimeDuration': arch['TimeDuration'], 'RotAmplitude': vec(arch['RotAmplitude'], (0, 0, 0)), 'RotFrequency': vec(arch['RotFrequency'], (0, 0, 0)),
         'LocAmplitude': vec(arch['LocAmplitude'], (0, 0, 0)), 'LocFrequency': vec(arch['LocFrequency'], (0, 0, 0)),
         'RotParams': dict((k, arch['RotParams'].get(k, 'ERS_Zero')) for k in 'XYZ'), 'LocParams': dict((k, arch['LocParams'].get(k, 'ERS_Zero')) for k in 'XYZ')}
    for k in ('RotAmplitude', 'RotFrequency', 'LocAmplitude', 'LocFrequency'):
        if ov and k in ov: r[k] = vec(ov[k], (0, 0, 0))   # whole member: absent axes are 0 in an authored vector
    if ov and 'TimeDuration' in ov: r['TimeDuration'] = ov['TimeDuration']
    for k in ('RotParams', 'LocParams'):
        if ov and k in ov:
            for ax in 'XYZ':
                if ax in ov[k]: r[k][ax] = ov[k][ax]
    return r

def emit(r):
    rnd = lambda p: ', '.join('true' if p[a] == 'ERS_Random' else 'false' for a in 'XYZ')
    return '{%.4ff, {%.1ff, %.1ff, %.1ff}, {%.2ff, %.2ff, %.2ff}, {%s}, {%.2ff, %.2ff, %.2ff}, {%.2ff, %.2ff, %.2ff}, {%s}}' % (
        r['TimeDuration'], *r['RotAmplitude'], *r['RotFrequency'], rnd(r['RotParams']), *r['LocAmplitude'], *r['LocFrequency'], rnd(r['LocParams']))

def main(audit, db, out):
    c = sqlite3.connect('file:%s?mode=ro' % db, uri=True)
    p = json.loads(c.execute("select props from objects where opath = 'TransGame.Default__TnWeaponMesh'").fetchone()[0])
    archS, archH = p['SpineRecoil'], p['RightHandRecoil']
    L = ['// GENERATED by tools/gameplay/gen_weapon_recoil.py - do not edit. {weapon id, spine RecoilDef, hand RecoilDef}: the TnWeaponMesh',
         '// archetype overlaid with each weapon mesh\'s authored SpineRecoil / RightHandRecoil (RE weapon presentation audit). "" = the archetype.',
         '// RecoilDef = {duration, rotAmp (rot units), rotFreq, rotRandom[3], locAmp (UU), locFreq, locRandom[3]}.',
         '    {"", %s, %s},' % (emit(resolve(archS, None)), emit(resolve(archH, None)))]
    for e in json.load(open(audit)):
        s, h = e.get('spine_recoil'), e.get('hand_recoil')
        if not s and not h: continue
        L.append('    {"%s", %s, %s},' % (e['id'], emit(resolve(archS, s)), emit(resolve(archH, h))))
    # Versus pickup weapons (TnWeaponPickupFactory) the audit does not list: their meshes' authored members straight from authored.db
    # (RE verification of f678bcf6). GatlingGun authors TimeDuration 0 / zero amplitudes: its controls are inert.
    for wid, mesh in (('HeavyRocketTurret', 'WEP_TurretRocket_p.Turret_Rocket_WEPMESH'), ('GatlingGun', 'WEP_TurretIonGun_p.TurretIonGun_WEPMESH')):
        r = c.execute('select props from objects where opath = ?', (mesh,)).fetchone()
        if not r: raise SystemExit('missing ' + mesh)
        p = json.loads(r[0] or '{}')
        L.append('    {"%s", %s, %s},' % (wid, emit(resolve(archS, p.get('SpineRecoil'))), emit(resolve(archH, p.get('RightHandRecoil')))))
    open(out, 'w', newline='\n').write('\n'.join(L) + '\n')
    print(len(L) - 3, 'rows ->', out)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3])
