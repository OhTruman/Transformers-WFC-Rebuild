# Generates src/game/WeaponCameraTable.inc from data/gameplay/weapons_mp.json: per weapon class, the camera recoil and per-shot shake the
# local player's camera applies (TnRecoilCameraBehavior / TnShakeCameraBehavior; RE PRESENTATION_AUDIT_2_RE.md + the camera recoil answer).
# Data selection (TnWeapon.GivenTo, CONFIRMED): TnMultiplayerGame wants MultiplayerData; a class without a MultiplayerData object uses
# PlayerData WHOLE (no per-field merge); fields missing in the chosen object are 0 (the struct defaults).
# Usage: python -I tools/gameplay/gen_weapon_camera.py <weapons_mp.json> <out.inc>
import json, sys

def main(src, out):
    d = json.load(open(src))
    ws = d['weapons']
    items = ws.items() if isinstance(ws, dict) else [(w.get('class'), w) for w in ws]
    rows = []
    for cls, w in items:
        if not cls or '.TnWeapon' not in cls: continue
        wid = cls.split('.TnWeapon', 1)[1]
        mp = w.get('MultiplayerData')
        data = mp if mp else w.get('PlayerData')
        vals = (data or {}).get('values', {}) if isinstance(data, dict) else {}
        r = vals.get('RecoilCameraParams') or {}
        s = vals.get('CameraShakeParams') or {}
        row = (wid, r.get('PitchAdjustmentDeg', 0.0), r.get('FovAdjustment', 0.0), r.get('RecoilTime', 0.0), r.get('RecoilDelay', 0.0),
               s.get('Intensity', 0.0), s.get('Roll', 0.0), s.get('RollFalloffDuration', 0.0), s.get('ShakeFalloffDuration', 0.0),
               'MultiplayerData' if mp else 'PlayerData')
        if any(abs(x) > 0 for x in row[1:9]): rows.append(row)
    rows.sort()
    L = ['// GENERATED by tools/gameplay/gen_weapon_camera.py from data/gameplay/weapons_mp.json - do not edit. Per weapon class suffix',
         '// (TransContent.TnWeapon<id>): RecoilCameraParams {PitchAdjustmentDeg, FovAdjustment, RecoilTime, RecoilDelay} and CameraShakeParams',
         '// {Intensity, Roll, RollFalloffDuration, ShakeFalloffDuration} of MultiplayerData, else PlayerData (whole object); missing fields 0.']
    for r in rows:
        L.append('    {"%s", %.4ff, %.4ff, %.4ff, %.4ff, %.4ff, %.4ff, %.4ff, %.4ff},   // %s' % r)
    open(out, 'w', newline='\n').write('\n'.join(L) + '\n')
    print(len(rows), 'weapons ->', out)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
