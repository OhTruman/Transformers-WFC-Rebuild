"""Generate src/game/VehicleHeadlights.inc from docs/handoff/SYSTEMS_VEHICLE_BEAMS.json (INVENTED PLACEMENT, Realistic-only;
Integration 2026-10-16) for Rendering's addTransientSpot (plan v3 row 3). Per vehicle: the picked lamp pair -> one spot per
lamp (high confidence) or one at the pair's midpoint (medium / low); a medium-confidence single -> one spot; otherwise none.
Each lamp is stored in the space of the body bone (C_Body_XB, else the root node) of vehicle.glb's bind pose, so it follows
the hovering / tilting body at runtime (World: boneWorld(bone) x local). Beam direction = the vehicle forward (+X) tilted
8 deg down, in the bone's space. Colour (Rendering's first pass) = lerp(warm white (1, 0.92, 0.80), the lamp emissive
normalised to max 1, 0.1) x 6. argv[1] = beams json, argv[2] = out .inc."""
import json, math, struct, sys
import numpy as np

ROOT = 'F:/Transformers Rebuild/ExtractedAssets/VerticalSlice/Characters'
TILT = math.radians(8.0)
WARM = np.array([1.0, 0.92, 0.80])
BRIGHT = 6.0

def node_globals(g):
    def local(n):
        m = np.eye(4)
        if 'matrix' in n:
            return np.array(n['matrix'], dtype=float).reshape(4, 4).T
        t = n.get('translation', [0, 0, 0]); r = n.get('rotation', [0, 0, 0, 1]); s = n.get('scale', [1, 1, 1])
        x, y, z, w = r
        R = np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                      [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                      [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])
        m[:3, :3] = R * np.array(s)[None, :]; m[:3, 3] = t
        return m
    parent = {}
    for i, n in enumerate(g['nodes']):
        for c in n.get('children', []):
            parent[c] = i
    G = {}
    def glob(i):
        if i not in G:
            G[i] = (glob(parent[i]) if i in parent else np.eye(4)) @ local(g['nodes'][i])
        return G[i]
    return {g['nodes'][i].get('name'): glob(i) for i in range(len(g['nodes']))}

beams = json.load(open(sys.argv[1], encoding='utf-8'))['vehicles']
rows = []
for cid, v in beams.items():
    k = v.get('pick', {})
    lamps = []
    if k.get('kind') == 'pair':
        L, R = k['L'], k['R']
        if k['confidence'] == 'high':
            lamps = [(L['pos_m'], L['emissive_linear']), ([R['pos_m'][0], R['pos_m'][1], -L['pos_m'][2]] if False else R['pos_m'], R['emissive_linear'])]
        else:
            lamps = [([(a + b) / 2 for a, b in zip(L['pos_m'], R['pos_m'])], [(a + b) / 2 for a, b in zip(L['emissive_linear'], R['emissive_linear'])])]
    elif k.get('kind') == 'single' and k['confidence'] == 'medium':
        lamps = [(k['C']['pos_m'], k['C']['emissive_linear'])]
    if not lamps:
        continue
    b = open(f'{ROOT}/{cid}/vehicle.glb', 'rb').read()
    n = struct.unpack_from('<I', b, 12)[0]
    G = node_globals(json.loads(b[20:20 + n]))
    bone = 'C_Body_XB' if 'C_Body_XB' in G else ('C_Reference_XR' if 'C_Reference_XR' in G else None)
    inv = np.linalg.inv(G[bone]) if bone else np.eye(4)
    fwd = np.array([math.cos(TILT), -math.sin(TILT), 0.0])
    for pos, em in lamps:
        p = inv @ np.array([*pos, 1.0])
        d = inv[:3, :3] @ fwd; d /= np.linalg.norm(d)
        e = np.array(em); e = e / max(e.max(), 1e-6)
        col = (WARM * 0.9 + e * 0.1) * BRIGHT
        rows.append('    {"%s", "%s", {%.4ff, %.4ff, %.4ff}, {%.4ff, %.4ff, %.4ff}, {%.3ff, %.3ff, %.3ff}},   // %s %s' % (
            cid, bone or '', *p[:3], *d, *col, k['kind'], k['confidence']))
with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tools/systems/gen_headlights.py from docs/handoff/SYSTEMS_VEHICLE_BEAMS.json; do not edit.\n'
            '// INVENTED PLACEMENT (no original headlights; Realistic-only addition, Integration 2026-10-16): chassis id, body bone,\n'
            '// lamp position and beam direction in that bone\'s space (metres; vehicle.glb bind pose), linear colour x brightness.\n')
    f.write('static const HeadlightDef kHeadlights[] = {\n' + '\n'.join(rows) + '\n};\n')
print(len(rows), 'spots for', len({r.split('"')[1] for r in rows}), 'vehicles ->', sys.argv[2])
