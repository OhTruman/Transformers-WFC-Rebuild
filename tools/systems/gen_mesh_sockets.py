"""Generate MeshSockets.inc from AssetTools authored.db (read only): every SkeletalMeshSocket of the WEP_* / TR_* skeletal meshes
(the sockets the authored anim notifies name: ShellEject, MagSocket, MuzzleFlash, BoosterSocket_*, Elbow / Knee / Wing trail
sockets, HoverFX_*, JumpBoostSocket_*, ...): {mesh opath, socket, bone, RelativeLocation UU (UE X, Y, Z), RelativeRotation
(UE units: pitch, yaw, roll), RelativeScale}. Supersedes DeathFx.inc's kDeathSockets subset for the notify dispatcher. Also the skeletal meshes of the MP transforming world
actors (AssetTools manifests/maps/mp_transforming_actors.json: IAC_InteriorDoor AUDIO_DOOR_CENTER for its door sounds).
Usage: python -I gen_mesh_sockets.py <authored.db> <out .inc>"""
import collections, io, json, sqlite3, sys
db = sqlite3.connect('file:%s?mode=ro' % sys.argv[1], uri=True)
TA_MANIFEST = 'F:/Transformers Rebuild/AssetTools/manifests/maps/mp_transforming_actors.json'
ta_meshes = sorted({a['skeletal_mesh'] for a in json.load(io.open(TA_MANIFEST, encoding='utf-8'))['actors'] if a.get('skeletal_mesh')})
rows = []
socks = list(db.execute("select opath, props from objects where class='SkeletalMeshSocket' and (opath like 'WEP\\_%' escape '\\' or opath like 'TR\\_%' escape '\\') order by opath"))
for m in ta_meshes:
    socks += list(db.execute("select opath, props from objects where class='SkeletalMeshSocket' and opath like ? escape '\\' order by opath",
                             (m.replace('_', '\\_') + '.%',)))
for o, pr in socks:
    p = json.loads(pr or '{}')
    n = p.get('SocketName')
    if not n: continue
    L = p.get('RelativeLocation') or {}; R = p.get('RelativeRotation') or {}; S = p.get('RelativeScale') or {}
    rows.append((o.rsplit('.', 1)[0], n, p.get('BoneName') or '', L.get('X', 0.0), L.get('Y', 0.0), L.get('Z', 0.0),
                 R.get('Pitch', 0), R.get('Yaw', 0), R.get('Roll', 0), S.get('X', 1.0) if S else 1.0))
q = lambda s: '"%s"' % s
out = ['// GENERATED by tools/systems/gen_mesh_sockets.py from AssetTools authored.db (read only); do not edit.',
       '// SkeletalMeshSocket of every WEP_* / TR_* skeletal mesh and of the MP transforming actors\' meshes: bone + relative location (UU,',
       '// UE axes) / rotation (UE units) / scale.',
       'struct MeshSocketRow { const char* mesh; const char* socket; const char* bone; float x, y, z; int pitch, yaw, roll; float scale; };',
       'static const MeshSocketRow kMeshSockets[] = {']
for m, n, b, x, y, z, pi, ya, ro, sc in rows:
    out.append('    {%s, %s, %s, %.3ff, %.3ff, %.3ff, %d, %d, %d, %.3ff},' % (q(m), q(n), q(b), x, y, z, pi, ya, ro, sc))
out.append('};')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
c = collections.Counter(r[1] for r in rows)
print('sockets', len(rows), '| meshes', len({r[0] for r in rows}), '| most common:', c.most_common(10))
