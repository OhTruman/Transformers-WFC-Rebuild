"""Generate src/game/DeathFx.inc from AssetTools authored.db (read only): the death-presentation effects the original's
TnDeathBlueprint entries name, for Gameplay's patch 2 call sites (World::spawnCorpse / gibCorpse / tickCorpses).
Per entry (TnDeathType<Name> -> "<Name>", first type of each Deaths entry, blueprint order):
  gibs: the entry's gib DSYS (UseCustomGibs ? GibsBlueprint (none = no gibs) : the blueprint's DefaultGibsBlueprint), as
        its effect-state factories: particle templates (+ local offset, UU), whether it spawns RB_Gib chunks, its sound cue;
  skeletal: the spawner (UseCustomSkeletalGibs ? SkeletalGibs : the blueprint's) exists AND has Templates;
  decals:   the applicator (UseCustomDecals ? DecalApplicator : the blueprint's) exists AND its Template has a Material;
  play effects: TnDeathModifierPlayEffect templates + socket names, the modifier's Delay max (s).
Plus TnPawn.GibbedCameraShake / GibbedShakeEffectDistance and TnPlayerController.DeathSound (the local player's death cue).
Usage: python -I gen_death_fx.py <authored.db> <out .inc>"""
import json, sqlite3, sys
db = sqlite3.connect('file:%s?mode=ro' % sys.argv[1], uri=True)
def props(o):
    r = db.execute('select props from objects where opath=?', (o,)).fetchone()
    return json.loads(r[0]) if r and r[0] else {}
def cls(o):
    r = db.execute('select class from objects where opath=?', (o,)).fetchone()
    return r[0] if r else None
def dsys(bp):
    """(templates [(name, x, y, z)], chunks, cue) of a gib DSYS's effect states (every state of every piece)."""
    fx, chunks, cue = [], False, ''
    if not bp: return fx, chunks, cue
    for (o,) in db.execute("select opath from objects where opath like ? and class='HmDestructionStateBlueprint'", (bp + '.%',)):
        for f in props(o).get('EffectFactories', []) or []:
            c, p = cls(f), props(f)
            if c == 'HmParticleDestructionEffectFactory' and p.get('Template'):
                pos = (p.get('Transform') or {}).get('Position') or {}
                fx.append((p['Template'], pos.get('X', 0.0), pos.get('Y', 0.0), pos.get('Z', 0.0)))
            elif c in ('HmGibsDestructionEffectFactory', 'HmDebrisDestructionEffectFactory'): chunks = True
            elif c == 'HmSoundDestructionEffectFactory' and p.get('Cue'): cue = p['Cue']
    return fx, chunks, cue
def q(s): return '"%s"' % s
out = ['// GENERATED by tools/systems/gen_death_fx.py from AssetTools authored.db (read only); do not edit.',
       '// The original death blueprints\' per-entry effects (Systems, for Gameplay patch 2). Offsets in UU, delays in s.', '']
rows = []
for bpname in ['TR_Deaths_p.SharedRobotDeaths', 'TR_Deaths_p.BruteRobotDeaths', 'TR_Deaths_p.SharedCarDeaths',
               'TR_Deaths_p.SharedTankDeaths', 'TR_Deaths_p.SharedJetDeaths', 'TR_Deaths_p.SharedVehicleDeaths']:
    bp = props(bpname)
    if not bp: continue
    for e in bp.get('Deaths', []) or []:
        types = e.get('Types') or []
        if not types: continue
        name = types[0].split('.')[-1].replace('TnDeathType', '')
        gbp = e.get('GibsBlueprint') if e.get('UseCustomGibs') else bp.get('DefaultGibsBlueprint')
        fx, chunks, cue = dsys(gbp)
        sg = e.get('SkeletalGibs') if e.get('UseCustomSkeletalGibs') else bp.get('SkeletalGibs')
        skel = bool(sg) and bool(props(sg).get('Templates'))   # a spawner with no Templates spawns nothing (car / tank / jet)
        da = e.get('DecalApplicator') if e.get('UseCustomDecals') else bp.get('DecalApplicator')
        dec = bool(da) and bool(((props(da).get('Template') or {}).get('Material')))   # an applicator with no Template material spawns nothing (vehicles)
        play = []; prand = False
        for m in e.get('Modifiers') or []:
            if cls(m) != 'TnDeathModifierPlayEffect': continue
            mp = props(m); dmax = ((mp.get('Delay') or {}).get('Max') or 0.0)
            prand = prand or mp.get('PlayType') == 'PET_Random'   # ETnPlayEffectsType: one of the listed effects, picked at random
            for ef in mp.get('Effects') or []:
                if ef.get('Template'): play.append((ef['Template'], ef.get('SocketName') or '', dmax))
        rows.append((bpname.split('.')[-1], name, gbp or '', fx, chunks, cue, skel, dec, play, prand))
    # "Default": no entry's types match (e.g. a damage type without a DamageDeathType, sideways momentum) -> the blueprint's own
    # DefaultGibsBlueprint / SkeletalGibs / DecalApplicator, no modifiers.
    fx, chunks, cue = dsys(bp.get('DefaultGibsBlueprint'))
    sg, da = bp.get('SkeletalGibs'), bp.get('DecalApplicator')
    rows.append((bpname.split('.')[-1], 'Default', bp.get('DefaultGibsBlueprint') or '', fx, chunks, cue, bool(sg) and bool(props(sg).get('Templates')),
                 bool(da) and bool((props(da).get('Template') or {}).get('Material')), [], False))
out.append('struct DeathFxTemplate { const char* tmpl; float x, y, z; };')
out.append('struct DeathPlayEffect { const char* tmpl; const char* socket; float delayMax; };')
out.append('struct DeathFxEntry { const char* blueprint; const char* entry; const char* gibsBlueprint; int nGibFx; DeathFxTemplate gibFx[3];')
out.append('                      bool chunks; const char* gibCue; bool skeletalGibs; bool decals; int nPlay; DeathPlayEffect play[3]; bool playRandom; };   // playRandom: PET_Random - ONE of play[] (uniform), else all')
out.append('static const DeathFxEntry kDeathFx[] = {')
for b, n, g, fx, ch, cue, sk, dc, pl, pr in rows:
    fxs = ', '.join('{%s, %.1ff, %.1ff, %.1ff}' % (q(t), x, y, z) for t, x, y, z in fx[:3]) or '{}'
    pls = ', '.join('{%s, %s, %.2ff}' % (q(t), q(s), d) for t, s, d in pl[:3]) or '{}'
    out.append('    {%s, %s, %s, %d, {%s}, %s, %s, %s, %s, %d, {%s}, %s},' % (q(b), q(n), q(g), min(len(fx), 3), fxs, 'true' if ch else 'false', q(cue),
               'true' if sk else 'false', 'true' if dc else 'false', min(len(pl), 3), pls, 'true' if pr else 'false'))
out.append('};')
# The death sockets per skeletal mesh (SkeletalMeshSocket: bone + RelativeLocation UU + RelativeRotation, UE axes).
SOCK = ('Head_FX', 'BoosterSocket_C', 'Chest_FX', 'TargetingSocket', 'VaporTrailSocket_R', 'PositionSocket')
out.append('struct DeathSocket { const char* mesh; const char* socket; const char* bone; float x, y, z; int pitch, yaw, roll; };')
out.append('static const DeathSocket kDeathSockets[] = {')
ns = 0
for o, pr in db.execute("select opath, props from objects where class='SkeletalMeshSocket' order by opath"):
    sp = json.loads(pr or '{}'); n = sp.get('SocketName')
    if n not in SOCK: continue
    mesh = o.rsplit('.', 1)[0]; L = sp.get('RelativeLocation') or {}; R = sp.get('RelativeRotation') or {}
    out.append('    {%s, %s, %s, %.2ff, %.2ff, %.2ff, %d, %d, %d},' % (q(mesh), q(n), q(sp.get('BoneName') or ''), L.get('X', 0.0), L.get('Y', 0.0), L.get('Z', 0.0),
               R.get('Pitch', 0), R.get('Yaw', 0), R.get('Roll', 0))); ns += 1
out.append('};')
print('sockets', ns)
pawn = props('TransGame.Default__TnPawn'); sh = pawn.get('GibbedCameraShake') or {}
out.append('// TnPawn.GibbedCameraShake (a gibbing pawn within GibbedShakeEffectDistance of the local view shakes it).')
out.append('struct GibbedShakeDef { float intensity, roll, rollFalloff, shakeFalloff, distanceUU; };')
out.append('static const GibbedShakeDef kGibbedCameraShake = {%.4ff, %.4ff, %.4ff, %.4ff, %.1ff};' % (
    sh.get('Intensity', 0.0), sh.get('Roll', 0.0), sh.get('RollFalloffDuration', 0.0), sh.get('ShakeFalloffDuration', 0.0), pawn.get('GibbedShakeEffectDistance', 0.0)))
pc = props('TransGame.Default__TnPlayerController')
out.append('// TnPlayerController.DeathSound: the local player\'s own death cue.')
out.append('static const char* const kLocalDeathCue = %s;' % q(pc.get('DeathSound') or ''))
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('entries', len(rows)); [print('  %-18s %-16s gibs=%s fx=%s chunks=%s cue=%s skel=%s decals=%s play%s=%s' % (b, n, g.split('.')[-1] or '-', [t.split('.')[-1] for t, *_ in fx], ch, cue or '-', sk, dc, '(ONE at random)' if pr else '', [(t.split('.')[-1], s) for t, s, _ in pl])) for b, n, g, fx, ch, cue, sk, dc, pl, pr in rows]
