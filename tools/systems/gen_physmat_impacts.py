"""Generate PhysmatImpacts.inc from AssetTools authored.db (read only): per PhysicalMaterial (every path the MP maps' collision_weapon_physmat.json
files name, plus any PhysicalMaterial authoring ImpactEffect / ImpactSound) its ImpactEffect, ImpactSound and ImpactThreshold /
ImpactReFireDelay, resolved up the PhysicalMaterial Parent chain. The impact rule (TnWeaponMesh, RE weapon audit section 1):
squib = physmat weapon-specific (none authored) -> PhysicalMaterial.ImpactEffect -> weapon DefaultSquib; sound the same with
ImpactSound -> weapon DefaultImpactSound. Usage: python -I gen_physmat_impacts.py <authored.db> <AssetTools manifests/maps> <out .inc>"""
import glob, json, os, sqlite3, sys
db = sqlite3.connect('file:%s?mode=ro' % sys.argv[1], uri=True)
paths = set()
for f in glob.glob(os.path.join(sys.argv[2], 'MP_*', 'collision_weapon_physmat.json')):
    d = json.load(open(f, encoding='utf-8'))
    paths.update(p for p in d.get('physmats', []) if p)
    if d.get('engine_default_physmat'): paths.add(d['engine_default_physmat'])
for (o,) in db.execute("select opath from objects where class='PhysicalMaterial' and (props like '%ImpactEffect%' or props like '%ImpactSound%')"):
    paths.add(o)
def props(o):
    r = db.execute('select props from objects where opath=?', (o,)).fetchone()
    return json.loads(r[0] or '{}') if r else {}
def resolved(o, key, depth=0):
    p = props(o)
    if p.get(key): return p[key]
    par = p.get('Parent')
    return resolved(par, key, depth + 1) if par and depth < 8 else None
rows = []
for o in sorted(paths):
    rows.append((o, resolved(o, 'ImpactEffect') or '', resolved(o, 'ImpactSound') or '', float(resolved(o, 'ImpactThreshold') or 0.0),
                 float(resolved(o, 'ImpactReFireDelay') or 0.0)))
q = lambda s: '"%s"' % s
out = ['// GENERATED by tools/systems/gen_physmat_impacts.py from AssetTools authored.db (read only); do not edit.',
       '// Per PhysicalMaterial: ImpactEffect / ImpactSound (resolved up the Parent chain) - the 2nd step of the impact rule.',
       'struct PhysmatImpactRow { const char* physmat; const char* impactEffect; const char* impactSound; float impactThreshold, reFireDelay; };',
       'static const PhysmatImpactRow kPhysmatImpacts[] = {']
for o, e, s, t, r in rows: out.append('    {%s, %s, %s, %.1ff, %.2ff},' % (q(o), q(e), q(s), t, r))
out.append('};')
open(sys.argv[3], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('physmats', len(rows), '| with an ImpactEffect', sum(1 for r in rows if r[1]), '| with an ImpactSound', sum(1 for r in rows if r[2]))
for r in rows:
    if r[1] or r[2]: print('  %-55s fx %-45s snd %s' % (r[0], r[1], r[2]))
