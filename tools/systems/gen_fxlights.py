"""Generate src/game/FxLights.inc (RT-era effect lights, Realistic only, WFC_FXLIGHTS=1 opt-in; Integration 2026-10-16) from
docs/handoff/SYSTEMS_RT_LIGHT_HOOKS.json (per effect template: normalised colour, proposed radius / brightness / duration)
and each MP vehicle's BoostFx sockets (ExtractedAssets/VerticalSlice/Characters/<id>/character.json: template, socket ->
bone + relative_location_gltf). These are additions, not original lights (the original has none for effects).
argv[1] = hooks json, argv[2] = out .inc."""
import json, glob, os, sys

def F(x):
    t = ('%.4f' % float(x)).rstrip('0')
    return (t + '0' if t.endswith('.') else t) + 'f'

# Calibration per kind on top of the hooks' proposals (Rendering, Realistic lockstep Streets / Gorge / Molten, transient gain 2,
# 2026-10-16): explosions read right (Streets m01500); impacts threw a green-white wash over a stretch of floor (Molten
# m01100) -> colour x 0.6 and a 0.15 s flash instead of a 0.25 s glow. Boost / pickups: rechecked in the eye pass.
# Eye pass (Rendering, Rust pick_504 step 840): a nearby explosion blew Rust's bright floor out to white -> explosion
# colour x 0.7 (radius / duration unchanged; Streets' explosion still reads strong at 0.7).
CALIBRATION = {'impact (spawnImpact)': {'colour': 0.6, 'duration_s': 0.15},   # keyed by the hooks' kind
               'explosion (radiusDamage / projectile impact)': {'colour': 0.7}}

rows = json.load(open(sys.argv[1], encoding='utf-8'))['rows']
fx = {}
for r in rows:
    if 'proposal' not in r:
        continue
    p = r['proposal']
    b = p['brightness']
    cal = CALIBRATION.get(r['kind'], {})
    col = [round(c * b * cal.get('colour', 1.0), 3) for c in r['colour']]
    dur = 0.0 if p['duration_s'] == 'continuous' else float(cal.get('duration_s', p['duration_s']))
    fx[r['template']] = (col, p['radius_m'], p['falloff'], dur, r['kind'])

L = ['// GENERATED by tools/systems/gen_fxlights.py from docs/handoff/SYSTEMS_RT_LIGHT_HOOKS.json + character.json BoostFx; do not edit.',
     '// RT-era effect lights (NOT original lights): Realistic only, on by default there (WFC_FXLIGHTS=0 off); impacts calibrated (CALIBRATION).',
     '// Effect template, linear colour x brightness, radius (m), falloff exponent, duration (s; 0 = continuous while active).',
     'static const FxLightDef kFxLights[] = {']
for t, (col, rad, fo, dur, kind) in sorted(fx.items()):
    L.append('    {"%s", {%s, %s, %s}, %s, %s, %s},   // %s' % (t, F(col[0]), F(col[1]), F(col[2]), F(rad), F(fo), F(dur), kind))
L.append('};')
L.append('// Per vehicle chassis: BoostFx socket bone + position in the bone\'s space (m, glTF), and the boost template\'s light.')
L.append('static const BoostLightDef kBoostLights[] = {')
n = 0
for p in sorted(glob.glob('F:/Transformers Rebuild/ExtractedAssets/VerticalSlice/Characters/*/character.json')):
    cid = os.path.basename(os.path.dirname(p))
    c = json.load(open(p, encoding='utf-8'))
    socks = {s['socket']: s for s in (c['vehicle'].get('sockets') or [])}
    for f in (c.get('vehicle_fx (VEHDEF particle structs; sockets on vehicle.glb)') or {}).get('BoostFx', []) or []:
        t, sk = f.get('template'), f.get('socket')
        if t not in fx or sk not in socks:
            continue
        col, rad, fo, dur, kind = fx[t]
        s = socks[sk]
        loc = s.get('relative_location_gltf') or [0, 0, 0]
        L.append('    {"%s", "%s", {%s, %s, %s}, {%s, %s, %s}, %s, %s},   // %s %s' % (cid, s['bone'], F(loc[0]), F(loc[1]), F(loc[2]), F(col[0]), F(col[1]), F(col[2]),
                 F(rad), F(fo), t.split('.')[-1], sk))
        n += 1
L.append('};')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
print(len(fx), 'effect templates,', n, 'boost sockets ->', sys.argv[2])
