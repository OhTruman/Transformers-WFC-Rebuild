"""Generate AnimNotifies.inc from AssetTools authored.db (read only): every HmAnimNotify_PlayEffect and HmAnimNotify_Sound
authored on the AnimSequences of the MP-relevant AnimSets (packages WEP_* = weapons, TR_* = characters / vehicles), as
{animset, sequence, time s, kind, what, socket, flags}. The runtime fires a row when the playing sequence's time crosses it
(forwards; FireWhenBackwards rows only when played backwards). Systems' authored FX / sound wiring item (package 7).
Usage: python -I gen_anim_notifies.py <authored.db> <out .inc>"""
import collections, json, sqlite3, sys
db = sqlite3.connect('file:%s?mode=ro' % sys.argv[1], uri=True)
rows = []
stats = collections.Counter()
def props(o):
    r = db.execute('select class, props from objects where opath=?', (o,)).fetchone()
    return (r[0], json.loads(r[1] or '{}')) if r else (None, {})
for opath, pr in db.execute("select opath, props from objects where class='AnimSequence' and (opath like 'WEP\\_%' escape '\\' or opath like 'TR\\_%' escape '\\')"):
    seq = json.loads(pr or '{}')
    animset = opath.rsplit('.', 1)[0]
    name = seq.get('SequenceName') or ''
    for n in seq.get('Notifies') or []:
        cls, p = props(n.get('Notify') or '')
        t = float(n.get('Time') or 0.0)
        if cls == 'HmAnimNotify_PlayEffect' and p.get('ParticleSystemTemplate'):
            rows.append((animset, name, t, 'Effect', p['ParticleSystemTemplate'], p.get('SocketName') or '', 1 if p.get('bAttach', True) else 0))
            stats['effect'] += 1
        elif cls == 'HmAnimNotify_Sound' and p.get('SoundCue'):
            fw, bw = p.get('FireWhenForwards', True), p.get('FireWhenBackwards', False)
            rows.append((animset, name, t, 'Sound', p['SoundCue'], '', (2 if bw else 0) | (0 if fw is False else 4)))
            stats['sound'] += 1
rows.sort()
q = lambda s: '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')
out = ['// GENERATED by tools/systems/gen_anim_notifies.py from AssetTools authored.db (read only); do not edit.',
       '// Authored AnimSequence notifies of the WEP_* / TR_* AnimSets: effects (HmAnimNotify_PlayEffect) and sounds (HmAnimNotify_Sound).',
       '// flags: Effect - 1 attach to the socket; Sound - 4 fire forwards, 2 fire backwards.',
       'struct AnimNotifyRow { const char* animSet; const char* sequence; float time; bool effect; const char* what; const char* socket; int flags; };',
       'static const AnimNotifyRow kAnimNotifies[] = {']
for a, s, t, k, w, so, f in rows:
    out.append('    {%s, %s, %.4ff, %s, %s, %s, %d},' % (q(a), q(s), t, 'true' if k == 'Effect' else 'false', q(w), q(so), f))
out.append('};')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
per = collections.Counter(r[0].split('.')[0] for r in rows)
print('rows', len(rows), dict(stats), '| animsets', len({r[0] for r in rows}))
for k, v in per.most_common(12): print('  %-40s %d' % (k, v))
