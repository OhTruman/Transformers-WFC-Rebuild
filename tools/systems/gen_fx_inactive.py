"""Generate src/render/gl/FxInactive.inc: the effective ParticleSystemComponent.SecondsBeforeInactive of every map-FX instance
(map_fx_runtime.json "component"), resolved in AssetTools authored.db (read only): the component's own value, else the first
value up its archetype chain (e.g. Engine.Default__Emitter.ParticleSystemComponent0 = 1.0, TnPickupFactory PickupEffect0 =
1.0), else 0 (never). UE3: a component unrendered for longer than this stops ticking (frozen, resumed when rendered again).
Only nonzero rows are written. Usage: python -I gen_fx_inactive.py <authored.db> <render data root> <out .inc>"""
import json, os, sqlite3, sys, collections
db = sqlite3.connect('file:%s?mode=ro' % sys.argv[1], uri=True)
root = sys.argv[2]
cache = {}
def sbi(o, depth=0):
    if o in cache: return cache[o]
    r = db.execute('select archetype, props from objects where opath=?', (o,)).fetchone()
    v = None
    if r:
        p = json.loads(r[1] or '{}')
        if 'SecondsBeforeInactive' in p: v = (float(p['SecondsBeforeInactive']), o)
        elif r[0] and depth < 12: v = sbi(r[0], depth + 1)
    cache[o] = v
    return v
rows, stats = [], collections.Counter()
for m in sorted(os.listdir(root)):
    f = os.path.join(root, m, 'map_fx_runtime.json')
    if not os.path.isfile(f): continue
    d = json.load(open(f, encoding='utf-8'))
    for x in d.get('instances') or d.get('components') or []:
        v = sbi(x['component'])
        stats[(m, 'resolved' if v else 'default0')] += 1
        if v and v[0] > 0: rows.append((m, x['component'], v[0], v[1], x.get('owner_class', '')))
out = ['// GENERATED by tools/systems/gen_fx_inactive.py from AssetTools authored.db (read only); do not edit.',
       '// Map-FX instances whose ParticleSystemComponent.SecondsBeforeInactive > 0 (the value and where it comes from).',
       'struct FxInactiveRow { const char* map; const char* component; float seconds; };',
       'static const FxInactiveRow kFxInactive[] = {']
for m, c, s, src, oc in rows: out.append('    {"%s", "%s", %.2ff},   // %s (%s)' % (m, c, s, src, oc))
out.append('};')
open(sys.argv[3], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
per = collections.Counter((m, s, oc) for m, c, s, src, oc in rows)
print('rows', len(rows)); [print(' ', k, n) for k, n in sorted(per.items())]
print('instances resolved / default 0:', sum(v for (m, k), v in stats.items() if k == 'resolved'), sum(v for (m, k), v in stats.items() if k == 'default0'))
