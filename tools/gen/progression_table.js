// Generates src/game/ProgressionTable.inc from RE-Workspace notes/data (mp_xp_events.json, mp_kill_awards.json,
// mp_challenge_stat_producers.json). Usage: node tools/gen/progression_table.js <RE notes/data dir>
const fs = require('fs'), path = require('path');
const dir = process.argv[2] || 'F:/Transformers Rebuild/RE-Workspace/notes/data';
const xp = JSON.parse(fs.readFileSync(path.join(dir, 'mp_xp_events.json'), 'utf8'));
const ka = JSON.parse(fs.readFileSync(path.join(dir, 'mp_kill_awards.json'), 'utf8'));
const sp = JSON.parse(fs.readFileSync(path.join(dir, 'mp_challenge_stat_producers.json'), 'utf8'));
const q = s => s == null ? 'nullptr' : JSON.stringify(String(s).replace(/^TransGame\./, ''));
const short = s => s == null ? null : String(s).replace(/^TransGame\./, '').replace(/^TnXpEventType/, '');
let o = [];
o.push('// GENERATED by tools/gen/progression_table.js from RE-Workspace notes/data (mp_xp_events.json, mp_kill_awards.json,');
o.push('// mp_challenge_stat_producers.json) [CONF RE MP_PROGRESSION_SCORING_AI 2026-10-06]. Do not edit by hand.');
o.push(`static const float kGlobalXpMultiplier = ${xp.GlobalXpMultiplier};`);
o.push('struct XpEventRow { const char* id; int xp; int dmXp; const char* announcement; const char* description; };');
o.push('static const XpEventRow kXpEvents[] = {');
for (const e of xp.events) o.push(`    {${q(short(e.class))}, ${e.XpAmount}, ${e.DeathmatchXpAmount == null ? -1 : e.DeathmatchXpAmount}, ${q(e.Announcement || '')}, ${q((e.Description || '').replace(/`k/g, ''))}},`);
o.push('};');
const rule = n => ka.rules.find(r => r.name === n);
o.push('struct BuffCheckRow { const char* buff; const char* xpEvent; const char* assistXpEvent; int statId; };');
for (const [n, v] of [['KillerBuffCheck', 'kKillerBuffChecks'], ['KilledDefensiveBuffCheck', 'kKilledDefensiveBuffChecks'], ['KilledOffensiveBuffCheck', 'kKilledOffensiveBuffChecks']]) {
  o.push(`static const BuffCheckRow ${v}[] = {`);
  for (const b of rule(n).config.BuffChecks) o.push(`    {${q(b.BuffClass)}, ${q(short(b.XpEvent))}, ${q(short(b.AssistXpEvent))}, ${b.StatId == null ? -1 : b.StatId}},`);
  o.push('};');
}
o.push('struct DamageCheckRow { const char* damageType; const char* xpEvent; int statId; };');
o.push('static const DamageCheckRow kDamageTypeChecks[] = {');
for (const d of rule('DamageTypeCheck').config.DamageChecks) o.push(`    {${q(d.DamageType)}, ${q(short(d.XpEvent))}, ${d.StatId == null ? -1 : d.StatId}},`);
o.push('};');
o.push(`static const float kLongRangeUU = ${rule('LongRange').config.LongDistance};`);
o.push(`static const int kFlagCarrierStatId = ${rule('FlagCarrier').config.StatId ?? -1};`);
o.push(`static const int kKillerDownedStatId = ${rule('KillerDowned').config.StatId ?? -1};`);
o.push('// TnKillAwardRuleSpecialtySpecific: stat-only kill checks per killer specialty (KilledForm VFT_*; empty = any).');
o.push('struct SpecialtyCheckRow { const char* specialty; const char* damageType; bool headshot; const char* killerBuff; const char* killedBuff; bool killerInVehicle; const char* killedForm; const char* killedSpecialty; int statId; };');
o.push('static const SpecialtyCheckRow kSpecialtyChecks[] = {');
for (const n of ['ScoutSpecific', 'ScientistSpecific', 'SoldierSpecific', 'LeaderSpecific']) {
  const r = rule(n);
  for (const c of r.config.KillChecks) o.push(`    {${q(r.config.SpecialtyName)}, ${q(c.DamageType)}, ${!!c.Headshot}, ${q(c.KillerBuff)}, ${q(c.KilledBuff)}, ${!!c.KillerInVehicle}, ${q(c.KilledForm === 'VFT_Invalid' ? '' : c.KilledForm)}, ${q(c.KilledSpecialty || '')}, ${c.StatId}},`);
}
o.push('};');
o.push('// Challenge stat ids by challenge name (StatPropertyIds).');
o.push('struct ChallengeStatRow { const char* challenge; int statId; };');
o.push('static const ChallengeStatRow kChallengeStats[] = {');
for (const k of Object.keys(sp)) o.push(`    {${q(sp[k].challenge)}, ${k}},`);
o.push('};');
fs.writeFileSync(path.join(__dirname, '../../src/game/ProgressionTable.inc'), o.join('\n') + '\n');
console.log('ok', xp.events.length, 'xp events');
